"""Convex decomposition of a mesh with CoACD (approximate convex decomposition, collision-aware) and an MJCF snippet
for MuJoCo: one visual mesh geom plus one collision geom per convex part. The snippet is checked by compiling it in a
scene with a floor and dropping the object until it rests.

params: name (object), threshold (concavity, 0.05; lower = more parts), max_parts (-1 = no limit), resolution (2000),
        preprocess (auto | on | off), mcts_iterations (150), max_hull_vertices (64), seed (0), center (true: body frame at the mesh's centre of
        mass), mass (kg; default from density), density (kg/m^3, 500), scale (1.0), freejoint (true), simulate (true),
        preview (true)
inputs: mesh (.obj, .glb, .stl, .ply)
outputs: <name>.xml (MJCF snippet, <include>-able), <name>_scene.xml (floor + the object, for checking),
         meshes/<name>_visual.obj, meshes/<name>_part_NNN.obj, parts.npz (part hull volumes), preview.png
         JSON: parts, part_vertices, hull_volume_m3, mesh_volume_m3, volume_ratio, body_pos, drop (rest height, speed)
"""

from __future__ import annotations

import numpy as np

from _common import PALETTE, main, threads, versions

LICENCE = "MIT (CoACD); Apache-2.0 (MuJoCo)"


def load_mesh(path: str, scale: float):
    import trimesh
    m = trimesh.load(path, force="mesh", process=True)
    if scale != 1.0:
        m.apply_scale(scale)
    return m


def decompose(mesh, req):
    import coacd
    coacd.set_log_level("warn")
    cm = coacd.Mesh(np.asarray(mesh.vertices, np.float64), np.asarray(mesh.faces, np.int32))
    kw = dict(threshold=float(req.get("threshold", 0.05)), max_convex_hull=int(req.get("max_parts", -1)),
              preprocess_mode=str(req.get("preprocess", "auto")), resolution=int(req.get("resolution", 2000)),
              mcts_iterations=int(req.get("mcts_iterations", 150)), seed=int(req.get("seed", 0)))
    try:      # at most max_hull_vertices per part (MuJoCo collides faster with small hulls)
        parts = coacd.run_coacd(cm, decimate=True, max_ch_vertex=int(req.get("max_hull_vertices", 64)), **kw)
    except TypeError:          # older coacd without decimate / max_ch_vertex
        parts = coacd.run_coacd(cm, **kw)
    return [(np.asarray(v, float), np.asarray(f, int)) for v, f in parts]


def mjcf(name: str, visual: str, part_files: list[str], pos, mass: float | None, density: float,
         freejoint: bool) -> str:
    assets = [f'    <mesh name="{name}_visual" file="{visual}"/>']
    assets += [f'    <mesh name="{name}_part_{i:03d}" file="{p}"/>' for i, p in enumerate(part_files)]
    mass_attr = f' mass="{mass / max(1, len(part_files)):.6g}"' if mass else f' density="{density:g}"'
    geoms = [f'      <geom name="{name}_visual" type="mesh" mesh="{name}_visual" contype="0" conaffinity="0" group="2" '
             f'mass="0" rgba="0.8 0.8 0.8 1"/>']
    for i in range(len(part_files)):
        c = PALETTE[i % len(PALETTE)]
        geoms.append(f'      <geom name="{name}_col_{i:03d}" type="mesh" mesh="{name}_part_{i:03d}" group="3"{mass_attr} '
                     f'rgba="{c[0] / 255:.3f} {c[1] / 255:.3f} {c[2] / 255:.3f} 1" friction="1 0.01 0.001"/>')
    joint = f'      <freejoint name="{name}_free"/>\n' if freejoint else ""
    p = " ".join(f"{x:.6g}" for x in pos)
    return (f'<mujoco model="{name}">\n  <!-- generated by hylo tool convex (CoACD): visual mesh (group 2) + '
            f'{len(part_files)} convex collision parts (group 3) -->\n'
            f'  <compiler meshdir="meshes"/>\n  <asset>\n' + "\n".join(assets) + "\n  </asset>\n  <worldbody>\n"
            f'    <body name="{name}" pos="{p}">\n{joint}' + "\n".join(geoms) + "\n    </body>\n  </worldbody>\n</mujoco>\n")


def scene_xml(name: str, floor_z: float) -> str:
    return (f'<mujoco model="{name}_check">\n  <include file="{name}.xml"/>\n  <option timestep="0.002"/>\n'
            f'  <worldbody>\n    <geom name="floor" type="plane" size="2 2 0.1" pos="0 0 {floor_z:.6g}" '
            f'rgba="0.6 0.6 0.6 1"/>\n    <light pos="0 0 2" dir="0 0 -1"/>\n  </worldbody>\n</mujoco>\n')


def drop_test(scene_path: str, name: str, seconds: float = 3.0) -> dict:
    import mujoco
    m = mujoco.MjModel.from_xml_path(scene_path)
    d = mujoco.MjData(m)
    bid = m.body(name).id
    mujoco.mj_forward(m, d)
    z0 = float(d.xpos[bid][2])
    n = int(seconds / m.opt.timestep)
    for _ in range(n):
        mujoco.mj_step(m, d)
    v = float(np.linalg.norm(d.qvel[:6])) if m.nv >= 6 else 0.0
    ok = bool(np.isfinite(d.qpos).all() and v < 0.05)
    floor_z = float(m.geom("floor").pos[2])
    lowest = min(float(d.geom_xpos[g][2] - m.geom_rbound[g]) for g in range(m.ngeom)
                 if m.geom_bodyid[g] == bid and m.geom_contype[g])
    return {"steps": n, "z_start": round(z0, 4), "z_rest": round(float(d.xpos[bid][2]), 4), "speed_end": round(v, 5),
            "settled": ok, "ncon": int(d.ncon), "ngeom": int(m.ngeom), "floor_z": round(floor_z, 4),
            "above_floor": bool(float(d.xpos[bid][2]) > floor_z and np.isfinite(lowest))}


def preview(mesh, parts) -> np.ndarray:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection
    fig = plt.figure(figsize=(8, 4), dpi=100)
    V = mesh.vertices
    lo, hi = V.min(0), V.max(0)
    mid, r = (hi + lo) / 2, (hi - lo).max() / 2
    light = np.array([0.3, -0.5, 0.8]) / np.linalg.norm([0.3, -0.5, 0.8])

    def draw(ax, verts, faces, col):
        tri = verts[faces]
        fn = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
        fn /= np.linalg.norm(fn, axis=1, keepdims=True) + 1e-12
        shade = 0.45 + 0.55 * np.clip(np.abs(fn @ light), 0, 1)
        ax.add_collection3d(Poly3DCollection(tri, facecolors=np.clip(np.array(col)[None] * shade[:, None], 0, 1),
                                             edgecolors="none"))

    m = mesh
    if len(m.faces) > 5000:
        try:
            m = m.simplify_quadric_decimation(face_count=5000)
        except Exception:  # noqa: BLE001
            pass
    for k, title in enumerate(["input mesh", f"{len(parts)} convex parts (CoACD)"]):
        ax = fig.add_subplot(1, 2, k + 1, projection="3d")
        if k == 0:
            draw(ax, m.vertices, m.faces, (0.75, 0.75, 0.78))
        else:
            for i, (v, f) in enumerate(parts):
                draw(ax, v, f, np.array(PALETTE[i % len(PALETTE)]) / 255)
        for a, (s, e) in zip("xyz", zip(mid - r, mid + r)):
            getattr(ax, f"set_{a}lim")(s, e)
        ax.view_init(elev=22, azim=-55)
        ax.set_title(title, fontsize=10)
        ax.set_axis_off()
    fig.tight_layout()
    fig.canvas.draw()
    img = np.asarray(fig.canvas.buffer_rgba())[..., :3].copy()
    plt.close(fig)
    return img


def handle(state, req):
    import trimesh
    name = str(req.get("name", "object"))
    mesh = load_mesh(req.input("mesh"), float(req.get("scale", 1.0)))
    if not mesh.is_watertight:
        trimesh.repair.fill_holes(mesh)
    pos = np.zeros(3)
    if req.get("center", True):
        pos = np.asarray(mesh.center_mass if mesh.is_watertight else mesh.bounds.mean(0), float)
        mesh.apply_translation(-pos)
    parts = decompose(mesh, req)
    mdir = req.out_dir / "meshes"
    mdir.mkdir(exist_ok=True)
    visual = f"{name}_visual.obj"
    mesh.export(mdir / visual)
    files, vols, nverts = [], [], []
    for i, (v, f) in enumerate(parts):
        pm = trimesh.Trimesh(v, f, process=True)
        fn = f"{name}_part_{i:03d}.obj"
        pm.export(mdir / fn)
        req.files[f"part_{i:03d}"] = str(mdir / fn)
        files.append(fn)
        vols.append(float(abs(pm.volume)))
        nverts.append(int(len(pm.vertices)))
    req.files["visual"] = str(mdir / visual)
    xml = mjcf(name, visual, files, pos, req.get("mass"), float(req.get("density", 500.0)),
               bool(req.get("freejoint", True)))
    req.path(f"{name}.xml", "mjcf").write_text(xml)
    floor_z = float(mesh.bounds[0][2] + pos[2]) - 0.01      # 1 cm below the object's lowest point
    scene = req.path(f"{name}_scene.xml", "scene")
    scene.write_text(scene_xml(name, floor_z))
    drop = drop_test(str(scene), name) if req.get("simulate", True) else None
    req.save_npz("parts", volumes=np.array(vols), vertices=np.array(nverts), body_pos=pos)
    if req.get("preview", True):
        req.save_png("preview", preview(mesh, parts))
    mesh_vol = float(mesh.volume) if mesh.is_watertight else None
    req.provenance.update({"model": "CoACD", "licence": LICENCE, "backend": "coacd.run_coacd",
                           "packages": versions("coacd", "trimesh", "mujoco"), "threads": threads()})
    return {"parts": len(parts), "part_vertices": nverts, "hull_volume_m3": round(sum(vols), 9),
            "mesh_volume_m3": mesh_vol, "volume_ratio": round(sum(vols) / mesh_vol, 4) if mesh_vol else None,
            "body_pos": pos.round(6).tolist(), "input_faces": int(len(mesh.faces)), "drop": drop,
            "mjcf_snippet": xml if len(xml) < 6000 else xml[:6000] + "\n<!-- truncated -->"}


if __name__ == "__main__":
    raise SystemExit(main(handle=handle))
