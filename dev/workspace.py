"""Write (or check) the uv workspace over the worldcurrent repositories checked out side by side.

    python harness/dev/workspace.py [DIR] [--check]

DIR (default: the directory holding this harness checkout) contains harness/, bench/, serve/, ... as listed in
repos.toml. The generated DIR/pyproject.toml makes every package of every present code repository a workspace
member and installs them all editable into one venv (`uv sync` in DIR). --check exits 1 if the file is stale.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

HARNESS = Path(__file__).resolve().parents[1]
GROUPS = ("packages", "adapters")


def render(root: Path) -> str:
    repos = tomllib.loads((HARNESS / "dev" / "repos.toml").read_text())["repos"]
    present = [r for r, spec in repos.items() if spec.get("code", True) and (root / r).is_dir()]
    members, names = [], []
    for repo in present:
        for group in GROUPS:
            found = sorted((root / repo / group).glob("*/pyproject.toml"))
            if found:
                members.append(f"{repo}/{group}/*")
                names += [tomllib.loads(p.read_text())["project"]["name"] for p in found]
    q = lambda xs: ", ".join(f'"{x}"' for x in xs)   # noqa: E731
    return "\n".join([
        "# Generated by harness/dev/workspace.py: the worldcurrent repositories side by side, one venv.",
        "[project]",
        'name = "worldcurrent-workspace"',
        'version = "0.0.0"',
        'requires-python = ">=3.10"',
        f"dependencies = [{q(names)}]",
        "",
        "[dependency-groups]",
        'dev = ["pytest>=8", "httpx>=0.27"]',
        'demo = ["imageio>=2.38.0", "imageio-ffmpeg>=0.7.0", "matplotlib>=3.10.9", "pillow>=12.3.0"]',
        "",
        "[tool.uv]",
        "package = false",
        "",
        "[tool.uv.workspace]",
        f"members = [{q(members)}]",
        "",
        "[tool.uv.sources]",
        *[f"{n} = {{ workspace = true }}" for n in names],
        "",
        "[tool.pytest.ini_options]",
        f"testpaths = [{q(present)}]",
        'addopts = "--import-mode=importlib"',
        "",
    ])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("dir", nargs="?", default=str(HARNESS.parent))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    root = Path(a.dir).resolve()
    text, target = render(root), root / "pyproject.toml"
    if a.check:
        if not target.exists() or target.read_text() != text:
            print(f"{target} is stale: run python {Path(__file__).relative_to(root)} {a.dir}", file=sys.stderr)
            return 1
        return 0
    target.write_text(text)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
